/**
 * 干扰文档生成器：模拟企业知识库中的相似文档噪声
 *
 * 动机：真实知识库中大量文档共享"请假/年假/报销/密码"等通用主题，
 * 这些相似文档是检索歧义的主要来源。8 份手写目标文档不足以制造竞争，
 * 因此用固定随机种子生成 32 份参数化的干扰文档（其他公司制度 / 技术笔记 / 杂项）。
 *
 * 设计原则：
 * - 固定种子（mulberry32 PRNG）保证每次生成的文档一致，评测可复现；
 * - 干扰文档与目标文档共享主题词但数值/规则不同，模拟多租户知识库的歧义场景；
 * - 生成物不提交到 git，由评测脚本在运行时生成（temp 目录）。
 *
 * 运行：pnpm tsx scripts/gen-noise-docs.ts <输出目录>
 */
import { writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";

// ---------- 固定种子 PRNG（mulberry32），保证可复现 ----------
function mulberry32(seed: number) {
  let a = seed >>> 0;
  return () => {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const rnd = mulberry32(20260922);
const pick = <T>(arr: T[]): T => arr[Math.floor(rnd() * arr.length)];
const between = (min: number, max: number) => min + Math.floor(rnd() * (max - min + 1));

// ---------- 模板素材 ----------
const COMPANIES = [
  "华信科技", "启明软件", "远航数据", "云图信息", "天工智能", "凌云网络",
  "博雅咨询", "新纪元数字", "恒达科技", "金桥软件", "瑞捷网络", "辰星数据",
];
const CITIES = ["北京", "上海", "广州", "杭州", "南京", "武汉", "成都", "西安", "苏州", "长沙"];
const OA_SYSTEMS = ["OA 系统", "ERP 系统", "钉钉", "飞书", "企业微信"];
const APPROVERS = ["部门经理", "部门总监", "分管副总", "总经理", "财务总监"];

function genCompanyDoc(name: string): string {
  const leaveDays = pick([1, 2, 3]);
  const annual = pick([5, 6, 8, 10, 12, 15]);
  const annualRule = pick(["转正后即可享受", "入职满一年后生效", "入职满两年后生效", "按季度折算发放"]);
  const reimburse = pick([2000, 3000, 4000, 6000, 8000]);
  const hotel = pick([200, 300, 400, 500]);
  const pwdLen = pick([8, 10, 12, 16]);
  const pwdDays = pick([30, 60, 90, 180]);
  const overtime = pick([
    "工作日加班按 1.5 倍时薪、周末 2 倍、节假日 3 倍计算，需提前在系统报备",
    "加班以调休补偿，调休需在 90 天内使用，未使用部分不折算",
    "加班 2 小时以上记半天调休，单日加班不超过 4 小时",
  ]);
  const city = pick(CITIES);
  const system = pick(OA_SYSTEMS);

  return `# ${name}员工管理制度（2026 修订版）

## 总则
本制度适用于${name}全体正式员工，自发布之日起施行。制度的解释权归人力资源部所有，修订需经总经理办公会审议通过。员工入职时需完成制度学习并签署确认书。

## 考勤打卡
公司使用${system}打卡，工作时间为 9:00 至 18:00，午休一小时。每月允许${pick([2, 3, 5])}次补卡机会，超出部分每次扣款 ${pick([10, 20, 30])} 元。核心工作时间全员需在岗，远程办公每周不超过${pick([1, 2, 3])}天。

## 请假规定
员工请假需提前 ${leaveDays} 天在${system}提交申请。事假每年累计不超过 ${pick([10, 12, 15, 20])} 天。年假每年 ${annual} 天，${annualRule}。病假需附医院诊断证明，婚假 ${pick([3, 7, 10])} 天，产假 158 天。

## 报销制度
单笔报销 ${reimburse} 元以内由${pick(APPROVERS)}审批，超过需${pick(APPROVERS)}加签。报销需在费用发生后 ${pick([30, 45, 60])} 天内提交，发票抬头为「${name}（${city}）有限公司」。差旅报销需附行程单与住宿水单。

## 差旅标准
出差住宿标准为每晚不超过 ${hotel} 元，机票提前 ${pick([2, 3, 5])} 个工作日预订经济舱，高铁二等座。市内交通实报实销，需留存行程单。出差餐补每人每天 ${pick([50, 60, 80, 100])} 元。

## 加班管理
${overtime}。加班餐补每次 ${pick([20, 30, 40])} 元，打车费用实报实销。

## 密码与信息安全
公司系统密码长度不低于 ${pwdLen} 位，需包含大小写字母与数字，每 ${pwdDays} 天强制更换一次。严禁在便签、聊天记录中保存密码，VPN 登录需使用动态令牌。

## 培训与绩效
新员工入职培训为期 ${pick([3, 5, 7, 10])} 天。绩效评估${pick(["每季度", "每半年", "每年"])}一次，考核维度包括工作产出与协作能力。连续两次评估优秀的员工进入晋升候选池。

## 员工福利
公司提供五险一金，每年组织一次体检。节日发放礼金，员工生日当月发放 ${pick([100, 200, 300])} 元生日券。年度团建人均预算 ${pick([300, 500, 800])} 元。
`;
}

function genTechDoc(idx: number): string {
  const names = [
    "数据平台运维手册", "订单系统技术方案", "推荐服务架构笔记", "前端性能优化记录",
    "消息队列使用规范", "缓存设计与实践", "机器学习工程笔记", "日志与监控方案",
  ];
  const name = names[idx % names.length];
  const qps = between(100, 5000);
  const rt = between(50, 500);

  return `# ${name}

## 背景与目标
本文档记录${name}的设计与实施要点，供团队内部参考。核心目标是在保障稳定性的前提下控制成本，方案变更需在技术评审会上确认。

## 架构设计
服务采用分层架构，接入层负责鉴权与限流，核心层处理业务逻辑，数据层使用读写分离。峰值 QPS 约 ${qps}，接口平均响应时间目标为 ${rt} 毫秒以内。核心链路设置熔断与降级策略，依赖服务超时阈值统一为 2 秒。

## 数据存储
业务数据使用 MySQL 主从结构，备份策略为每日全量、每小时增量，备份保留 ${pick([7, 14, 30])} 天。热点数据使用 Redis 缓存，缓存过期时间按业务场景设置，防止缓存雪崩与击穿。

## 性能优化
查询性能优化优先看索引覆盖与慢查询日志，接口性能优化关注序列化与网络往返。批量操作合并请求，异步任务使用消息队列削峰。前端资源开启压缩与缓存，图片使用懒加载。

## 监控告警
监控指标包括 QPS、错误率、P99 延迟与资源水位。告警分为提醒与紧急两级，紧急告警 5 分钟内响应。日志统一收集到日志平台，保留 ${pick([30, 90, 180])} 天。

## 安全规范
API Key 与数据库密码存放在密钥管理系统中，禁止硬编码。生产环境操作需双人复核，变更需留痕。敏感数据展示需脱敏，导出需审批。

## 复盘与迭代
每次线上事故后 48 小时内完成复盘，输出根因分析与改进项。改进项跟踪到责任人，两周内关闭率达到 90% 以上。
`;
}

function genMiscDoc(idx: number): string {
  const names = [
    "Q3 项目周报汇总", "技术分享会会议纪要", "新员工学习路线", "知识库建设规范",
    "团队协作公约", "代码评审指南", "数据指标口径说明", "内部工具使用手册",
  ];
  const name = names[idx % names.length];
  return `# ${name}

## 本周进展
各项目按计划推进，整体进度正常。存在的主要风险是${pick(["测试资源不足", "需求变更频繁", "第三方接口不稳定", "排期冲突"])}，已安排专项跟进，预计下周给出解决方案。

## 关键数据
本周完成需求 ${between(5, 30)} 个，修复缺陷 ${between(3, 20)} 个，线上可用性 99.9%。核心指标的环比变化需结合活动与版本发布因素解读，避免单一数据得出结论。

## 经验沉淀
团队沉淀了${pick(["检索优化", "性能调优", "部署流程", "数据处理"])}方面的经验，建议整理成文档放入知识库。文档编写遵循「背景-方案-结论」结构，附上可复现的示例代码。

## 下周计划
优先处理${pick(["核心链路优化", "用户反馈高频问题", "技术债清理", "新版本发布准备"])}。周会时间调整为每周三下午，会议时长控制在 40 分钟内。

## 附则
本文档为内部资料，未经许可不得外传。对内容有疑问请联系文档负责人。
`;
}

function main() {
  const outDir = process.argv[2] ?? join(process.cwd(), ".tmp-noise-docs");
  mkdirSync(outDir, { recursive: true });

  // 12 份公司制度干扰文档（与目标文档共享"请假/年假/报销/密码"主题词）
  for (let i = 0; i < COMPANIES.length; i++) {
    writeFileSync(join(outDir, `制度-${COMPANIES[i]}员工管理制度.md`), genCompanyDoc(COMPANIES[i]), "utf-8");
  }
  // 12 份技术类干扰文档
  for (let i = 0; i < 12; i++) {
    writeFileSync(join(outDir, `技术-${String(i + 1).padStart(2, "0")}.md`), genTechDoc(i), "utf-8");
  }
  // 8 份杂项干扰文档
  for (let i = 0; i < 8; i++) {
    writeFileSync(join(outDir, `杂项-${String(i + 1).padStart(2, "0")}.md`), genMiscDoc(i), "utf-8");
  }

  console.log(`已生成 32 份干扰文档 → ${outDir}`);
}

main();
